ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN credential_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE account_tokens (
 id UUID PRIMARY KEY,user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 purpose VARCHAR(10) NOT NULL CHECK(purpose IN ('RESET','VERIFY')),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX account_tokens_owner ON account_tokens(user_id,purpose);
CREATE TABLE email_outbox (
 id UUID PRIMARY KEY,user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 payload TEXT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt TIMESTAMP WITH TIME ZONE NOT NULL,expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,sent_at TIMESTAMP WITH TIME ZONE
);

